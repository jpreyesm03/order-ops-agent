"""Confirmation summaries, argument fingerprints, data provenance and variant ranking (D31).

The gate uses these so that:
  - what the customer confirms is generated by code from the exact call that will run (C1), including what the
    change rules out afterwards (C3);
  - every address, payment method and item id in a change comes from the customer's words or from data a tool
    returned in this conversation (C2);
  - variant choice can be checked option by option (C4).
"""
from __future__ import annotations

import hashlib
import json
import re
from collections.abc import Callable
from decimal import Decimal
from typing import Any

ADDRESS_FIELDS = ("address1", "address2", "city", "state", "country", "zip")
ID_FIELDS = ("payment_method_id",)
LIST_ID_FIELDS = ("item_ids", "new_item_ids")
ONE_SHOT = {  # changes an order accepts only once, and what they rule out
    "exchange_delivered_order_items": "After this, the order can't be returned, exchanged or changed again.",
    "return_delivered_order_items": "After this, the order can't be returned again or exchanged.",
    "modify_pending_order_items": "After this, the order's items, address and payment can't be changed and it "
                                  "can't be cancelled.",
}
ACTION = {
    "cancel_pending_order": "Cancel order", "exchange_delivered_order_items": "Exchange items on order",
    "return_delivered_order_items": "Return items from order", "modify_pending_order_items": "Change items on order",
    "modify_pending_order_address": "Change the shipping address of order",
    "modify_pending_order_payment": "Change the payment method of order",
    "modify_user_address": "Change the default address of account",
}
DONE = {
    "cancel_pending_order": "Order {t} is cancelled.",
    "exchange_delivered_order_items": "Exchange requested on order {t}.",
    "return_delivered_order_items": "Return requested on order {t}.",
    "modify_pending_order_items": "Items changed on order {t}.",
    "modify_pending_order_address": "Shipping address of order {t} changed.",
    "modify_pending_order_payment": "Payment method of order {t} changed.",
    "modify_user_address": "Default address of account {t} changed.",
}


def done(tool: str, args: dict[str, Any], pending_approval: bool = False) -> str:
    """One line, rendered by code, telling the customer that a confirmed change ran."""
    target = args.get("order_id") or args.get("user_id")
    if pending_approval:
        return f"Submitted for supervisor approval: {ACTION.get(tool, tool).lower()} {target}."
    return "Done: " + DONE.get(tool, tool + " {t}.").format(t=target)


_ABBR = {"street": "st", "avenue": "ave", "drive": "dr", "road": "rd", "boulevard": "blvd", "lane": "ln",
         "suite": "ste", "apartment": "apt", "court": "ct", "place": "pl", "north": "n", "south": "s",
         "east": "e", "west": "w", "united states": "usa", "us": "usa"}


# ---------- fingerprint ----------
def canonical(tool: str, args: dict[str, Any]) -> str:
    """Arguments in a form that ignores order where order doesn't matter (pairs of old→new items stay paired)."""
    a = {k: (v.strip() if isinstance(v, str) else v) for k, v in args.items()}
    if isinstance(a.get("item_ids"), list) and isinstance(a.get("new_item_ids"), list):
        pairs = sorted(zip(a.pop("item_ids"), a.pop("new_item_ids"), strict=False))
        a["pairs"] = pairs
    elif isinstance(a.get("item_ids"), list):
        a["item_ids"] = sorted(a["item_ids"])
    return json.dumps({"tool": tool, "args": a}, sort_keys=True)


def fingerprint(tool: str, args: dict[str, Any]) -> str:
    return hashlib.sha256(canonical(tool, args).encode()).hexdigest()[:16]


# ---------- provenance ----------
def norm(text: str) -> str:
    """Lowercase, punctuation to spaces, common street words abbreviated, whitespace collapsed."""
    t = re.sub(r"[^\w\s]", " ", str(text).lower())
    t = " " + " ".join(t.split()) + " "
    for long, short in _ABBR.items():
        t = t.replace(f" {long} ", f" {short} ")
    return " ".join(t.split())


def unsourced(args: dict[str, Any], seen: str) -> list[str]:
    """Values in a change that appear neither in the customer's messages nor in tool results ("" is fine)."""
    corpus = " " + norm(seen) + " "
    missing = []
    for k in ADDRESS_FIELDS + ID_FIELDS:
        v = args.get(k)
        if isinstance(v, str) and v.strip() and f" {norm(v)} " not in corpus:
            missing.append(f"{k} '{v}'")
    for k in LIST_ID_FIELDS:
        for v in args.get(k) or []:
            if isinstance(v, str) and f" {norm(v)} " not in corpus:
                missing.append(f"{k} '{v}'")
    return missing


# ---------- summary ----------
def _money(x: Decimal | float | str) -> str:
    return f"${Decimal(str(x)):,.2f}"


def _opts(options: dict | None) -> str:
    return ", ".join(f"{k} {v}" for k, v in (options or {}).items())


def summary(tool: str, args: dict[str, Any], order: dict | None, variant: Callable[[str], dict | None],
            needs_approval: bool = False) -> str:
    """The confirmation the customer sees, built only from the call's arguments and the store's data."""
    target = args.get("order_id") or args.get("user_id")
    lines = ["Please confirm this change. Reply \"yes\" to go ahead, or tell me what to change.",
             f"- {ACTION.get(tool, tool)} {target}" + (f" (status: {order['status']})" if order else "")]
    items = {i["item_id"]: i for i in (order or {}).get("items", [])}
    if tool == "cancel_pending_order":
        for it in (order or {}).get("items", []):
            lines.append(f"  - {it['name']} ({_opts(it.get('options'))}) {_money(it['price'])}")
        lines.append(f"- Reason: {args.get('reason')}")
        lines.append("- The whole order is cancelled; the refund goes to the original payment method.")
    elif tool in ("exchange_delivered_order_items", "modify_pending_order_items"):
        diff = Decimal("0")
        for old, new in zip(args.get("item_ids", []), args.get("new_item_ids", []), strict=False):
            o, n = items.get(old), variant(new)
            if o is None or n is None:
                lines.append(f"  - item {old} → item {new}")
                continue
            diff += Decimal(str(n["price"])) - Decimal(str(o["price"]))
            same = " (same item!)" if old == new else ""
            lines.append(f"  - {o['name']}: {_opts(o.get('options'))} {_money(o['price'])} → "
                         f"{_opts(n.get('options'))} {_money(n['price'])}{same}")
        word = "charge" if diff > 0 else "refund"
        lines.append(f"- Price difference: {word} {_money(abs(diff))} using {args.get('payment_method_id')}")
    elif tool == "return_delivered_order_items":
        total = Decimal("0")
        for i in args.get("item_ids", []):
            it = items.get(i)
            if it is None:
                lines.append(f"  - item {i}")
                continue
            total += Decimal(str(it["price"]))
            lines.append(f"  - {it['name']} ({_opts(it.get('options'))}) {_money(it['price'])}")
        lines.append(f"- Refund {_money(total)} to {args.get('payment_method_id')}")
    elif tool in ("modify_pending_order_address", "modify_user_address"):
        addr = ", ".join(str(args.get(k)) for k in ADDRESS_FIELDS if args.get(k))
        lines.append(f"- New address: {addr}")
    elif tool == "modify_pending_order_payment":
        lines.append(f"- New payment method: {args.get('payment_method_id')}")
    if tool in ONE_SHOT and order:
        chosen = set(args.get("item_ids") or [])
        others = [f"{i['name']} ({_opts(i.get('options'))})" for i in order.get("items", [])
                  if i["item_id"] not in chosen]
        if others:
            lines.append("- Also on this order, NOT included: " + "; ".join(others))
        lines.append("- " + ONE_SHOT[tool])
    if needs_approval:
        lines.append("- This amount needs a supervisor's approval before it is final.")
    return "\n".join(lines)


# ---------- variants ----------
def rank_variants(product: dict, wanted: dict[str, str]) -> dict[str, Any]:
    """Variants of a product ranked by how many wanted options they match; every option value is listed so
    near-synonyms ("Google Home" / "Google Assistant") are visible."""
    variants = product.get("variants") or {}
    values: dict[str, set] = {}
    rows = []
    for item_id, v in variants.items():
        opts = v.get("options") or {}
        for k, x in opts.items():
            values.setdefault(k, set()).add(str(x))
        match, differs = [], []
        for k, want in (wanted or {}).items():
            have = str(opts.get(k, ""))
            (match if norm(want) and (norm(want) in norm(have) or norm(have) in norm(want)) else differs).append(k)
        rows.append({"item_id": item_id, "options": opts, "available": bool(v.get("available")),
                     "price": v.get("price"), "matches": len(match), "differs_on": differs})
    rows.sort(key=lambda r: (-r["matches"], not r["available"], float(r["price"] or 0)))
    return {"product_id": product.get("product_id"), "name": product.get("name"),
            "option_values": {k: sorted(s) for k, s in values.items()},
            "best_matches": rows[:8],
            "note": "matches = wanted options found in the variant; check 'differs_on' and 'available'. Option "
                    "names can differ from the customer's words; match by meaning and confirm with them."}
